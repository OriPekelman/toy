#!/usr/bin/env ruby
# Generate the CUDA-backend mirror of a CPU FFI source file by
# mechanical substitution. The CPU file is the source of truth; the
# CUDA file is the build artifact (committed so reviewers see both).
#
# Phase 0.6 — graph-inlining refactor. The Spinel ivar-collision that
# made an `include Module` approach impractical doesn't matter here:
# we still get two distinct compiled classes (Spinel-friendly), but
# one human-readable Ruby file.
#
# Usage:
#   prep/gen_cuda_mirror.rb [file1 file2 ...]
#       -> regenerate the CUDA mirror for each input (default: every
#          file in MIRRORABLE below).
#
#   prep/gen_cuda_mirror.rb --verify [file ...]
#       -> compare each on-disk CUDA file against what we'd generate;
#          exit non-zero on drift. Use in CI / `make verify-mirrors`.
#
# === Sentinel syntax ===
#
# To carry a CPU-only block over the mirror line, wrap it:
#
#     # CUDA-MIRROR-SKIP-BEGIN: <reason>
#     <CPU-only code, any length>
#     # CUDA-MIRROR-SKIP-END
#
# The block is dropped from the CUDA mirror. Optionally precede the
# skipped lines with one or more STUB lines whose contents replace
# the block in the CUDA mirror:
#
#     # CUDA-MIRROR-SKIP-BEGIN: trace-tap is CPU-only diagnostic
#     # CUDA-MIRROR-STUB: def trace_tap(_name, t)
#     # CUDA-MIRROR-STUB:   t
#     # CUDA-MIRROR-STUB: end
#     def trace_tap(name_, t)
#       if @trace_on
#         ...full CPU implementation...
#       end
#       t
#     end
#     # CUDA-MIRROR-SKIP-END
#
# In the CUDA mirror, the three STUB lines become uncommented Ruby
# code in place of the original method body. STUB lines must appear
# *before* the first non-sentinel non-comment line of the block.

require "fileutils"

MIRRORABLE = [
  "lib/llama_seq_forward_ffi.rb",   # M3 (sequence-mode forward + LoRA)
  "lib/toy_smollm2_ffi_kv.rb",      # KV-cache decode (Phase 0.6 step 2)
]

# Per-input substitution tables. Each input file gets a custom table
# because class names + headers differ. Order matters: longer-suffix
# variants must come first so we don't double-rename (e.g. don't run
# `TinyNN → TinyNNCuda` after we've already produced `TinyNNCuda`).
SUBS_BY_FILE = {
  "lib/llama_seq_forward_ffi.rb" => [
    [/^# lib\/llama_seq_forward_ffi\.rb.*$/,
     "# lib/llama_seq_forward_ffi_cuda.rb — CUDA mirror of lib/llama_seq_forward_ffi.rb.\n" +
     "#\n" +
     "# AUTO-GENERATED by prep/gen_cuda_mirror.rb. Do not edit by hand;\n" +
     "# edit the CPU source and re-run the generator. The CPU file's\n" +
     "# header explains the architecture; this mirror keeps the same\n" +
     "# contract on the GPU backend via TinyNNCuda."],
    [/\bLlamaSeqForwardFFICache\b/, "LlamaSeqForwardFFICacheCuda"],
    [/\bLlamaSeqBlockFFI\b/,        "LlamaSeqBlockFFICuda"],
    [/\bTinyNN\.\b/,                "TinyNNCuda."],
    [/\bTinyNN\b/,                  "TinyNNCuda"],
    [/tnn_session_new\(0\)/,        "tnn_session_new(1)"],
    [/^require_relative "tinynn"$/, 'require_relative "tinynn_cuda"'],
  ],

  "lib/toy_smollm2_ffi_kv.rb" => [
    [/^# lib\/toy_smollm2_ffi_kv\.rb.*$/,
     "# lib/toy_smollm2_ffi_kv_cuda.rb — CUDA mirror of lib/toy_smollm2_ffi_kv.rb.\n" +
     "#\n" +
     "# AUTO-GENERATED by prep/gen_cuda_mirror.rb. Do not edit by hand;\n" +
     "# edit the CPU source and re-run the generator. The CPU file's\n" +
     "# header explains the architecture; this mirror keeps the same\n" +
     "# contract on the GPU backend via TinyNNCuda."],
    # Class names — longer ones first (KV before KVBlock would be wrong:
    # KV is a substring of KVBlock once renamed). Use word boundaries.
    [/\bSmolLM2KVStepResult\b/,    "SmolLM2KVStepResultCuda"],
    [/\bSmolLM2KVFFICache\b/,      "SmolLM2KVFFICacheCuda"],
    [/\bSmolLM2KVBlockFFI\b/,      "SmolLM2KVBlockFFICuda"],
    # Module — the ".decode_step" wrapper. SmolLM2KV (without trailing
    # word char) only matches the module name, not the class names
    # (which now end in Cache/Block/Result -- already renamed).
    [/\bSmolLM2KV\.decode_step\b/, "SmolLM2KVCuda.decode_step"],
    [/\bSmolLM2KV\.upload_from\b/, "SmolLM2KVCuda.upload_from"],
    [/^module SmolLM2KV$/,         "module SmolLM2KVCuda"],
    # FFI module + backend selector.
    [/\bTinyNN\.\b/,               "TinyNNCuda."],
    [/\bTinyNN\b/,                 "TinyNNCuda"],
    [/tnn_session_new\(0\)/,       "tnn_session_new(1)"],
    [/^require_relative "tinynn"$/, 'require_relative "tinynn_cuda"'],
  ],
}

SKIP_OPEN   = /^\s*# CUDA-MIRROR-SKIP-BEGIN(?::.*)?$/
SKIP_CLOSE  = /^\s*# CUDA-MIRROR-SKIP-END\s*$/
STUB_LINE   = /^\s*# CUDA-MIRROR-STUB:\s?(.*)$/

def generate(cpu_path, subs)
  src = File.read(cpu_path)
  out_lines = []
  i = 0
  lines = src.lines
  while i < lines.length
    line = lines[i]
    if line =~ SKIP_OPEN
      # Scan the entire SKIP block, collect every STUB line (they may
      # appear anywhere inside, intermixed with comments and code),
      # then advance past SKIP-END.
      stub_lines = []
      j = i + 1
      while j < lines.length && lines[j] !~ SKIP_CLOSE
        if lines[j] =~ STUB_LINE
          stub_lines << $1 + "\n"
        end
        j += 1
      end
      stub_lines.each { |s| out_lines << s }
      i = j + 1  # past SKIP-END
      next
    end
    transformed = line.dup
    subs.each { |re, replacement| transformed.gsub!(re, replacement) }
    out_lines << transformed
    i += 1
  end
  out_lines.join
end

def derive_cuda_path(cpu_path)
  raise "expected lib/X_ffi*.rb, got #{cpu_path}" unless cpu_path =~ /_ffi(_[a-z]+)?\.rb$/
  cpu_path.sub(/\.rb$/, "_cuda.rb")
end

verify_only = ARGV.delete("--verify")
inputs      = ARGV.empty? ? MIRRORABLE : ARGV

drift = false
inputs.each do |cpu_path|
  unless File.exist?(cpu_path)
    $stderr.puts "[gen_cuda_mirror] missing: #{cpu_path}"
    drift = true
    next
  end
  subs = SUBS_BY_FILE[cpu_path]
  unless subs
    $stderr.puts "[gen_cuda_mirror] no substitution table for #{cpu_path}"
    drift = true
    next
  end
  # llama_seq_forward_ffi.rb -> llama_seq_forward_ffi_cuda.rb;
  # toy_smollm2_ffi_kv.rb -> toy_smollm2_ffi_kv_cuda.rb.
  cuda_path = cpu_path.sub(/\.rb$/, "_cuda.rb")
  generated = generate(cpu_path, subs)
  if verify_only
    actual = File.exist?(cuda_path) ? File.read(cuda_path) : ""
    if actual == generated
      puts "[gen_cuda_mirror] ok: #{cuda_path} matches generator"
    else
      puts "[gen_cuda_mirror] DRIFT: #{cuda_path} does not match generator output"
      puts "                  edit #{cpu_path} (the source of truth) and re-run"
      puts "                  prep/gen_cuda_mirror.rb #{cpu_path}"
      drift = true
    end
  else
    File.write(cuda_path, generated)
    puts "[gen_cuda_mirror] wrote #{cuda_path} (#{generated.lines.size} lines)"
  end
end

exit(drift ? 1 : 0) if verify_only
